
 // ========================================
// ゲーム全体の流れ
// 毎回「動かす → 描く」をくり返す
// ========================================

// ゲーム全体の状態
let gameState = "title";
let score = 0;


// ========================================
// ゲームを最初の値に戻す
// ========================================

function resetGame() {

  // プレイヤーと敵の初期化
  resetPlayer();
  resetEnemies();

  // スコアをリセット
  score = 0;
}


// ========================================
// ゲーム開始
// ========================================

function startGame() {

  // ゲームの初期化
  resetGame();

  // プレイ状態にする
  gameState = "play";
}


// ========================================
// ゲーム全体のキーボードイベント処理
// ========================================

document.addEventListener("keydown", (e) => {

  // ----------------------------------------
  // Enterキー：ゲーム開始・再スタート
  // ----------------------------------------

  if (e.code === "Enter") {

    if (gameState === "title" || gameState === "gameover") {
      startGame();
    }

  }


  // ----------------------------------------
  // Pキー：ポーズ・再開
  // ----------------------------------------

  if (e.code === "KeyP") {

    if (gameState === "play") {

      // プレイ中ならポーズ
      gameState = "pause";

    } else if (gameState === "pause") {

      // ポーズ中なら再開
      gameState = "play";

    }

  }

});


// ========================================
// クリックでもゲーム開始・再スタート
// ========================================

canvas.addEventListener("pointerdown", () => {

  if (gameState === "title" || gameState === "gameover") {
    startGame();
  }

});


// ========================================
// ゲーム全体の更新
// ========================================

function update(dt) {

  // プレイ中でなければ動かさない
  if (gameState !== "play") {
    return;
  }

  // プレイヤーの前回の足元を記録
  const prevBottom = player.y + player.h;


  // ----------------------------------------
  // プレイヤーと敵を動かす
  // ----------------------------------------

  updatePlayer(dt);

  spawnEnemies(dt);

  updateEnemies(dt);


  // ----------------------------------------
  // 敵との当たり判定
  // ----------------------------------------

  collideWithEnemies(prevBottom);


  // ----------------------------------------
  // HPがなくなったらゲームオーバー
  // ----------------------------------------

  if (player.hp <= 0) {
    gameState = "gameover";
  }

}


// ========================================
// メッセージ表示
// ========================================

function drawMessage(text, sub) {

  ctx.fillStyle = "#e8eeff";
  ctx.textAlign = "center";


  // メインメッセージ
  ctx.font = "32px sans-serif";
  ctx.fillText(text, canvas.width / 2, 150);


  // サブメッセージ
  ctx.font = "16px sans-serif";
  ctx.fillText(sub, canvas.width / 2, 190);


  // 文字設定を元に戻す
  ctx.textAlign = "left";
  ctx.font = "14px monospace";

}


// ========================================
// 点数とHP（HUD）
// ========================================

function drawHud() {

  // ----------------------------------------
  // スコア表示
  // ----------------------------------------

  ctx.fillStyle = "#e8eeff";
  ctx.fillText("SCORE " + score, 500, 20);


  // ----------------------------------------
  // HPバーの枠
  // ----------------------------------------

  ctx.strokeStyle = "#e8eeff";
  ctx.strokeRect(500, 30, 120, 12);


  // ----------------------------------------
  // HPバーの中身
  // HPの割合に応じて長さを変える
  // ----------------------------------------

  ctx.fillStyle = "#7ef5e1";

  ctx.fillRect(
    500,
    30,
    120 * player.hp / MAX_HP,
    12
  );

}


// ========================================
// ゲーム全体の描画
// ========================================

function draw() {

  // 画面を一度消す
  ctx.clearRect(0, 0, canvas.width, canvas.height);


  // ----------------------------------------
  // ステージを描く
  // ----------------------------------------

  drawStage();


  // ----------------------------------------
  // タイトル画面
  // ----------------------------------------

  if (gameState === "title") {

    drawMessage("my game", "Enter で始める");

    drawAim();

    return;

  }


  // ----------------------------------------
  // プレイヤーと敵を描く
  // ----------------------------------------

  drawPlayer();

  drawEnemies();

  drawHud();


  // ----------------------------------------
  // ポーズ画面
  // ----------------------------------------

  if (gameState === "pause") {

    drawMessage("PAUSE", "P でつづける");

  }


  // ----------------------------------------
  // ゲームオーバー画面
  // ----------------------------------------

  if (gameState === "gameover") {

    drawMessage("GAME OVER", "Enter でもう一度");

  }


  // ----------------------------------------
  // 照準を描く
  // ----------------------------------------

  drawAim();

}


// ========================================
// 時間管理
// ========================================

// 前回のフレーム時間
let last = performance.now();


// ========================================
// ゲームループ
// ========================================

function loop(now) {

  // 前回からの経過時間を秒に変換
  // 最大0.033秒に制限して、大きな時間差を防ぐ
  const dt = Math.min((now - last) / 1000, 0.033);

  // 今回の時間を次回用に保存
  last = now;


  // ----------------------------------------
  // ゲームを更新して描画
  // ----------------------------------------

  update(dt);

  draw();


  // 次のフレームを予約
  requestAnimationFrame(loop);

}


// ========================================
// ゲーム開始時にループを実行
// ========================================

requestAnimationFrame(loop);
